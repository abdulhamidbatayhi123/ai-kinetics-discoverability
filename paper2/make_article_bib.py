"""Build paper2/bib_article.tex: the entries of the shared paper2/bib_p2.tex that article.tex
cites, in order of first citation (Nature style numbers references in that order; with
natbib's numbers option the order of the bibitems sets the numbers). LaTeX comment lines are
ignored when looking for citations. Prints the keys cited but missing from bib_p2.tex (should be
none) and the number kept.

    python paper2/make_article_bib.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
BS = chr(92)   # a backslash, kept out of string literals on purpose


def cited_keys(tex):
    keys = []
    for line in tex.splitlines():
        line = re.sub(r"(?<!" + re.escape(BS) + r")%.*", "", line)   # drop comments, keep \%
        for group in re.findall(re.escape(BS) + r"cite[pt]?\{([^}]*)\}", line):
            for k in group.split(","):
                k = k.strip()
                if k and k not in keys:
                    keys.append(k)
    return keys


def bib_entries(bib):
    """{key: entry text including its trailing comment lines} from the shared bibliography."""
    parts = re.split(r"(?=^" + re.escape(BS) + r"bibitem\{)", bib, flags=re.M)
    head, out = parts[0], {}
    for p in parts[1:]:
        key = re.match(re.escape(BS) + r"bibitem\{([^}]*)\}", p).group(1)
        out[key] = p.replace(BS + "end{thebibliography}", "").rstrip() + "\n"
    return head, out


def main():
    tex = open(os.path.join(HERE, "article.tex"), encoding="utf-8").read()
    bib = open(os.path.join(HERE, "bib_p2.tex"), encoding="utf-8").read()
    keys = cited_keys(tex)
    head, entries = bib_entries(bib)
    missing = [k for k in keys if k not in entries]
    end = BS + "end{thebibliography}"
    begin = re.search(re.escape(BS) + r"begin\{thebibliography\}\{[^}]*\}", head)
    lines = ["% Generated by paper2/make_article_bib.py from bib_p2.tex: the entries article.tex",
             "% cites, in order of first citation. Do not edit by hand.",
             begin.group(0) if begin else BS + "begin{thebibliography}{99}", ""]
    lines += [entries[k] for k in keys if k in entries]
    lines.append(end)
    open(os.path.join(HERE, "bib_article.tex"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("kept", len(keys) - len(missing), "of", len(entries), "| missing:", missing)


if __name__ == "__main__":
    main()
